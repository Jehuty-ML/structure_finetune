def _out(
    think: str,
    utter: str,
    emotion: str,
    volume: int,
    pace: str,
    should_speak: bool,
    intent: str,
    ui_mode: str,
    end_turn: bool,
) -> str:
    payload = {
        "utter": utter,
        "emotion": emotion,
        "volume": volume,
        "pace": pace,
        "should_speak": should_speak,
        "intent": intent,
        "ui_mode": ui_mode,
        "end_turn": end_turn,
    }
    body = json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
    return f"<think>\n{think}\n</think>\n\n[json]\n{body}\n[/json]"


def _row(
    sid: str,
    user_text: str,
    user_emotion: str,
    think: str,
    utter: str,
    emotion: str,
    volume: int,
    pace: str,
    intent: str,
    *,
    scenario: str,
    energy: int = 55,
    bond: int = 4,
    turn: int = 3,
    can_speak: bool = True,
    interruptible: bool = True,
    should_speak: bool | None = None,
    ui_mode: str | None = None,
    end_turn: bool = False,
    prior_utters: list[str] | None = None,
    multi_turn: bool = False,
    round_i: int | None = None,
) -> dict[str, Any]:
    if should_speak is None:
        should_speak = can_speak
    if ui_mode is None:
        ui_mode = "speak" if can_speak else "text_only"
    if not can_speak:
        should_speak = False
        ui_mode = "text_only"
        volume = 0
    meta: dict[str, Any] = {
        "scenario": scenario,
        "contract": "v3",
        "source": "handcrafted",
    }
    if multi_turn:
        meta["multi_turn"] = True
        if round_i is not None:
            meta["round"] = round_i
    return {
        "id": sid,
        "input": {
            "user_text": user_text,
            "user_emotion": user_emotion,
            "session": {"energy": energy, "bond": bond, "turn": turn},
            "device": {"can_speak": can_speak, "interruptible": interruptible},
        },
        "output": _out(
            think, utter, emotion, volume, pace, should_speak, intent, ui_mode, end_turn
        ),
        "prior_utters": list(prior_utters or []),
        "meta": meta,
    }


