def split_train_val(
    rows: list[dict[str, Any]], val_ratio: float = 0.15, seed: int = 3407
) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    rng = random.Random(seed)
    shuffled = list(rows)
    rng.shuffle(shuffled)
    n_val = max(1, int(len(shuffled) * val_ratio))
    if n_val >= len(shuffled):
        n_val = max(1, len(shuffled) // 5)
    return shuffled[n_val:], shuffled[:n_val]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--val-ratio", type=float, default=0.15)
    parser.add_argument("--seed", type=int, default=3407)
    parser.add_argument("--out-dir", default=str(OUT_DIR))
    args = parser.parse_args()

    rows = build_single_turns() + build_multi_turns()
    # id 唯一
    ids = [r["id"] for r in rows]
    if len(ids) != len(set(ids)):
        raise SystemExit("存在重复 id")

    bad = 0
    for row in rows:
        vr = validate_turn(
            row["output"], schema_path=SCHEMA, input_obj=row.get("input")
        )
        if not vr.ok:
            bad += 1
            print(f"失败 {row['id']}: {vr.errors}")
    if bad:
        raise SystemExit(f"手写数据校验失败：{bad}/{len(rows)}")

    train, val = split_train_val(rows, val_ratio=args.val_ratio, seed=args.seed)
    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    for name, part in (("train.json", train), ("val.json", val)):
        (out_dir / name).write_text(
            json.dumps(part, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
        )
    sample = train[:3] + [r for r in train if r.get("prior_utters")][:1]
    (out_dir / "train_sample.json").write_text(
        json.dumps(sample[:4], ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )

    utters = []
    for r in rows:
        # 粗提 utter
        start = r["output"].find('"utter":"') + 9
        end = r["output"].find('","emotion"', start)
        utters.append(r["output"][start:end])
    print(
        f"手写样本 total={len(rows)} train={len(train)} val={len(val)} "
        f"unique_utter={len(set(utters))} multi={sum(1 for r in rows if r['prior_utters'] or r['meta'].get('multi_turn'))}"
    )
    print(f"已写入 -> {out_dir}")
    print("全部通过契约校验。")


if __name__ == "__main__":
    main()
