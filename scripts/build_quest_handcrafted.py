def _row(
    sid: str,
    rule_id: str,
    user_text: str,
    think: str,
    say: str,
    abstract: str,
    *,
    hp: str,
    mp: str,
    loc: str,
    quest: str,
    flags: str,
    prior_utters: list[str] | None = None,
    multi_turn: bool = False,
    round_i: int | None = None,
) -> dict[str, Any]:
    rule = RULES[rule_id]
    stats = {"hp": hp, "mp": mp, "loc": loc, "quest": quest, "flags": flags}
    out = render_quest_output(
        think,
        dict(rule["state"]),
        say,
        dict(rule["cmd"]),
        stats,
        abstract,
    )
    meta: dict[str, Any] = {
        "scenario": rule_id,
        "contract": "quest_v2_handcrafted",
        "rule_id": rule_id,
        "source": "handcrafted",
    }
    if multi_turn:
        meta["multi_turn"] = True
        if round_i is not None:
            meta["round"] = round_i
    return {
        "id": sid,
        "input": {
            "user_text": user_text,
            "fsm": dict(rule["fsm_in"]),
            "stats": {
                "hp": hp,
                "mp": mp,
                "loc": loc,
                "quest": quest,
            },
        },
        "output": out,
        "prior_utters": list(prior_utters or []),
        "meta": meta,
    }


