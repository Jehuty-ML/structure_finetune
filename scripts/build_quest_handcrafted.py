def _row(
    sid: str,
    rule_id: str,
    user_text: str,
    think: str,
    say: str,
    abstract: str,
    *,
    hp: str,
    mp: str,
    loc: str,
    quest: str,
    flags: str,
    hp_in: str | None = None,
    loc_in: str | None = None,
    prior_utters: list[str] | None = None,
    multi_turn: bool = False,
    round_i: int | None = None,
    state_override: dict[str, str] | None = None,
    cmd_override: dict[str, str] | None = None,
    fsm_in_override: dict[str, str] | None = None,
) -> dict[str, Any]:
    rule = RULES[rule_id]
    state = dict(state_override or rule["state"])
    cmd = dict(cmd_override or rule["cmd"])
    fsm_in = dict(fsm_in_override or rule["fsm_in"])
    stats = {"hp": hp, "mp": mp, "loc": loc, "quest": quest, "flags": flags}
    out = render_quest_output(
        think,
        state,
        say,
        cmd,
        stats,
        abstract,
    )
    meta: dict[str, Any] = {
        "scenario": rule_id,
        "contract": "quest_v2_handcrafted",
        "rule_id": rule_id,
        "source": "handcrafted",
    }
    if multi_turn:
        meta["multi_turn"] = True
        if round_i is not None:
            meta["round"] = round_i
    if loc_in is not None:
        input_loc = loc_in
    elif rule_id == "explore_move" and fsm_in.get("node") == "forest_fork":
        input_loc = "森林路口"
    else:
        input_loc = loc
    return {
        "id": sid,
        "input": {
            "user_text": user_text,
            "fsm": fsm_in,
            "stats": {
                "hp": hp_in if hp_in is not None else hp,
                "mp": mp,
                "loc": input_loc,
                "quest": quest,
            },
        },
        "output": out,
        "prior_utters": list(prior_utters or []),
        "meta": meta,
    }


